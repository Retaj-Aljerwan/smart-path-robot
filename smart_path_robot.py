@ev.button_b_pressed   # Task 2 : avoiding obstacles
def pressedb():        # the robot will avoid the obstacles when we press B
    rocky.forward(50, 1)
    while True:
        if rocky.color_ir_sensor.is_obstacle_ahead():
            rocky.turn_left_by_degree(90)
            rocky.forward(50, 1)
            rocky.turn_right_by_degree(90)
            rocky.forward(50, 1)
        elif rocky.color_ir_sensor.is_obstacle_ahead():
            rocky.turn_left_by_degree(90)
            rocky.forward(50, 1)
        else:
            rocky.forward(50, 2)



 #*************************************************

@ev.button_c_pressed  # Task 3 : line following
def pressedc():       # the robot will follow the line when we press C
    while True:
        readsensor = rocky.color_ir_sensor
        if readsensor.is_color('white'):
            while not not readsensor.is_color('white'):
                rocky.turn_right_by_degree(2)
        else:
            while not readsensor.is_color('white'):
                rocky.turn_left_by_degree(2)
        rocky.forward(3, 0.4)