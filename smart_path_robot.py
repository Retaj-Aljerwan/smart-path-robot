import codey as cd
import rocky
import event as ev
import time

@ev.button_a_pressed
def presseda():  # Task 1 : color detection
    time.sleep(2) # the robot will detect the colors when we press A
    mysensor = rocky.color_ir_sensor
    checkit = mysensor.is_color
    if checkit('red'):
        cd.emotion.look_down()
        cd.led.show(255, 0, 0, 3)
        cd.display.show_image("red", time_s=5)
        cd.display.clear()
    elif checkit('green'):
        cd.emotion.look_down()
        cd.led.show(140, 255, 0, mysensor.get_red())
        cd.display.show("Green", wait=False)
        time.sleep(5)
        cd.display.clear()
    elif checkit('blue'):
        cd.emotion.look_down()
        cd.led.show(0, 33, 255, 3)
        cd.display.show("Blue", wait=False)
        time.sleep(5)
        cd.display.clear()
    elif checkit('yellow'):
        cd.emotion.look_down()
        cd.led.show(255, 233, 0, 3)
        cd.display.show("Yellow", wait=False)
        time.sleep(5)
        cd.display.clear()
    elif checkit('cyan'):
        cd.emotion.look_down()
        cd.led.show(0, 255, 255, 3)
        cd.display.show("Cyan", wait=False)
        time.sleep(5)
        cd.display.clear()
    elif checkit('purple'):
        cd.emotion.look_down()
        cd.led.show(255, 0, 182, 3)
        cd.display.show("Purple", wait=False)
        time.sleep(5)
        cd.display.clear()
    elif checkit('black'):
        cd.emotion.look_down()
        cd.led.show(0, 0, 0, 3)
        cd.display.show("Black", wait=False)
        time.sleep(5)
        cd.display.clear()
    elif checkit('white'):
        cd.led.show(255, 255, 255, 3)
        cd.display.show("White", wait=False)
        time.sleep(5)
        cd.display.clear()
    else:
        cd.display.show("error")
